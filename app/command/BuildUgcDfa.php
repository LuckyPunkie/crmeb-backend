<?php

declare(strict_types=1);

namespace app\command;

use think\console\Command;
use think\console\Input;
use think\console\Output;

class BuildUgcDfa extends Command
{
    protected function configure()
    {
        $this->setName('ugc:build-dfa')
            ->setDescription('Build UGC sensitive-word DFA from crmeb/data/sensitive-words');
    }

    protected function execute(Input $input, Output $output)
    {
        $dir = root_path() . 'crmeb' . DIRECTORY_SEPARATOR . 'data' . DIRECTORY_SEPARATOR . 'sensitive-words';
        if (!is_dir($dir)) {
            $output->error('Missing dir: ' . $dir);
            return 1;
        }
        $words = [];
        foreach (scandir($dir) ?: [] as $name) {
            if ($name === '.' || $name === '..') {
                continue;
            }
            if (!preg_match('/\.txt$/u', $name)) {
                continue;
            }
            if (stripos($name, 'LICENSE') !== false) {
                continue;
            }
            $path = $dir . DIRECTORY_SEPARATOR . $name;
            $raw = file_get_contents($path);
            if ($raw === false) {
                continue;
            }
            $raw = preg_replace("/^\xEF\xBB\xBF/", '', $raw);
            $lineBased = (mb_strpos($name, '涉枪') !== false) || (mb_strpos($name, '违法') !== false);
            if ($lineBased) {
                foreach (preg_split('/\R/u', $raw) as $line) {
                    $line = trim($line);
                    if ($line !== '') {
                        $words[$line] = true;
                    }
                }
            } else {
                foreach (preg_split('/[,，\s]+/u', $raw) as $part) {
                    $part = trim($part);
                    if ($part !== '') {
                        $words[$part] = true;
                    }
                }
            }
            $output->writeln('read ' . $name);
        }
        $list = array_keys($words);
        usort($list, static function ($a, $b) {
            return mb_strlen($b, 'UTF-8') <=> mb_strlen($a, 'UTF-8');
        });
        $root = [];
        foreach ($list as $word) {
            $node = &$root;
            foreach (preg_split('//u', $word, -1, PREG_SPLIT_NO_EMPTY) as $ch) {
                if (!isset($node[$ch])) {
                    $node[$ch] = [];
                }
                $node = &$node[$ch];
            }
            $node['__end'] = 1;
            unset($node);
        }
        $outFile = root_path() . 'crmeb' . DIRECTORY_SEPARATOR . 'data' . DIRECTORY_SEPARATOR . 'ugc_sensitive_dfa.php';
        $payload = var_export(['__word_count' => count($list), 'nodes' => $root], true);
        file_put_contents($outFile, "<?php\n// Auto-generated by php think ugc:build-dfa\nreturn {$payload};\n");
        $output->writeln('words: ' . count($list));
        $output->writeln('written: ' . $outFile);
        return 0;
    }
}